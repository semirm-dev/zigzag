const testing = std.testing;

const TestTree = struct {
    tmp: testing.TmpDir,
    root: []const u8,

    fn init(arena: std.mem.Allocator) !TestTree {
        var tmp = testing.tmpDir(.{});
        errdefer tmp.cleanup();
        const root = try std.fs.path.join(arena, &.{ ".zig-cache", "tmp", &tmp.sub_path });
        return .{ .tmp = tmp, .root = root };
    }

    fn deinit(self: *TestTree) void {
        self.tmp.cleanup();
    }

    fn roots(self: TestTree) Roots {
        return .{ .go = self.root };
    }
};

test "an unreadable scaffold is kept, not clobbered" {
    var arena_state: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const io = testing.io;

    var tree = try TestTree.init(arena);
    defer tree.deinit();

    // A directory where the scaffold would go: readFileAlloc fails with
    // something other than FileNotFound, which the old code read as "absent".
    try tree.tmp.dir.createDirPath(io, "wrapper.go");
    try tree.tmp.dir.writeFile(io, .{ .sub_path = "wrapper.go/keep.txt", .data = "mine\n" });

    const files = [_]gen.OutFile{.{
        .lang = .go,
        .path = "wrapper.go",
        .bytes = "// generated\n",
        .tier = .user_scaffold,
    }};

    const actions = try writeFiles(io, arena, tree.roots(), &files, .{});
    try testing.expectEqual(@as(usize, 1), actions.len);
    try testing.expectEqual(Action.skipped_exists, actions[0].action);

    // The user's tree is untouched.
    const kept = try tree.tmp.dir.readFileAlloc(io, "wrapper.go/keep.txt", arena, .limited(1 << 10));
    try testing.expectEqualStrings("mine\n", kept);
}

test "an unreadable generated file fails loudly instead of being overwritten" {
    var arena_state: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const io = testing.io;

    var tree = try TestTree.init(arena);
    defer tree.deinit();

    try tree.tmp.dir.createDirPath(io, "blocked_gen.go");

    const files = [_]gen.OutFile{
        .{ .lang = .go, .path = "first_gen.go", .bytes = "// one\n" },
        .{ .lang = .go, .path = "blocked_gen.go", .bytes = "// two\n" },
        .{ .lang = .go, .path = "third_gen.go", .bytes = "// three\n" },
    };

    // The caller-owned list survives the error: what reached disk is reportable.
    var actions: std.ArrayList(FileAction) = .empty;
    try testing.expectError(
        error.IsDir,
        writeFilesInto(io, arena, tree.roots(), &files, .{}, &actions),
    );
    try testing.expectEqual(@as(usize, 1), actions.items.len);
    try testing.expectEqualStrings("first_gen.go", std.fs.path.basename(actions.items[0].path));
    try testing.expectEqual(Action.created, actions.items[0].action);

    // The third file was never reached, so it is not on disk either.
    try testing.expectError(
        error.FileNotFound,
        tree.tmp.dir.readFileAlloc(io, "third_gen.go", arena, .limited(1 << 10)),
    );
}

test "writeFiles creates, leaves unchanged, overwrites and keeps a scaffold" {
    var arena_state: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const io = testing.io;

    var tree = try TestTree.init(arena);
    defer tree.deinit();

    const files = [_]gen.OutFile{
        .{ .lang = .go, .path = "lib_ffi_gen.go", .bytes = "// v1\n" },
        .{ .lang = .go, .path = "wrapper.go", .bytes = "// scaffold\n", .tier = .user_scaffold },
    };

    const first = try writeFiles(io, arena, tree.roots(), &files, .{});
    try testing.expectEqual(Action.created, first[0].action);
    try testing.expectEqual(Action.created, first[1].action);

    const again = try writeFiles(io, arena, tree.roots(), &files, .{});
    try testing.expectEqual(Action.unchanged, again[0].action);
    try testing.expectEqual(Action.skipped_exists, again[1].action);

    const changed = [_]gen.OutFile{
        .{ .lang = .go, .path = "lib_ffi_gen.go", .bytes = "// v2\n" },
        .{ .lang = .go, .path = "wrapper.go", .bytes = "// regenerated\n", .tier = .user_scaffold },
    };
    const third = try writeFiles(io, arena, tree.roots(), &changed, .{});
    try testing.expectEqual(Action.overwritten, third[0].action);
    try testing.expectEqual(Action.skipped_exists, third[1].action);

    const scaffold = try tree.tmp.dir.readFileAlloc(io, "wrapper.go", arena, .limited(1 << 10));
    try testing.expectEqualStrings("// scaffold\n", scaffold);

    const forced = try writeFiles(io, arena, tree.roots(), &changed, .{ .force = true });
    try testing.expectEqual(Action.overwritten, forced[1].action);
    const rewritten = try tree.tmp.dir.readFileAlloc(io, "wrapper.go", arena, .limited(1 << 10));
    try testing.expectEqualStrings("// regenerated\n", rewritten);
}

test "a dry run reports without touching the filesystem" {
    var arena_state: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const io = testing.io;

    var tree = try TestTree.init(arena);
    defer tree.deinit();

    const files = [_]gen.OutFile{.{ .lang = .go, .path = "lib_ffi_gen.go", .bytes = "// v1\n" }};
    const actions = try writeFiles(io, arena, tree.roots(), &files, .{ .dry_run = true });
    try testing.expectEqual(Action.created, actions[0].action);
    try testing.expectError(
        error.FileNotFound,
        tree.tmp.dir.readFileAlloc(io, "lib_ffi_gen.go", arena, .limited(1 << 10)),
    );
}
